'use strict';
// Keep the legacy voice bank for standalone public/index.html. The main game
// uses byte-identical external clips so the bank is not on its critical path.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), crypto = require('node:crypto');
const root = path.join(__dirname, '../public/game'), context = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'vo.js'), 'utf8'), context);
const urls = {};
fs.mkdirSync(path.join(root, 'voices'), {recursive:true});
for (const [key, data] of Object.entries(context.window.VO_DATA)) {
  if (!/^[a-z0-9_]+$/.test(key)) throw new Error('Invalid voice key');
  const bytes = Buffer.from(data, 'base64');
  const name = `${key}.${crypto.createHash('sha256').update(bytes).digest('hex').slice(0,10)}.mp3`;
  fs.writeFileSync(path.join(root, 'voices', name), bytes);
  urls[key] = `voices/${name}`;
}
fs.writeFileSync(path.join(root, 'voice-manifest.js'), '// Generated by scripts/extract-voice-clips.cjs. No audio payload on the critical path.\nwindow.level29VoiceFiles=' + JSON.stringify(urls) + ';\n');
